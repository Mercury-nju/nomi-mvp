import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { expect } from '@playwright/test';
import { writeFile } from 'node:fs/promises';

const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROME_PATH || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome' });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
const checks = [];
const pass = name => checks.push({ name, passed: true });
const open = path => page.goto(`http://localhost:5174${path}`);
const listCount = async () => Number((await page.locator('.nc-list-caption').innerText()).match(/共 (\d+) 人/)[1]);
try {
  await open('/results');
  await page.locator('#potential-customers').waitFor();
  assert.deepEqual(await page.locator('.wr-metric-value').allTextContents(), ['3,860人', '550人', '355人', '47人']);
  for (const [name, count] of [['分析用户', 3860], ['目标客户', 550], ['成功触达', 355], ['留资客户', 47]]) {
    await page.getByRole('button', { name: `查看${name}明细，共${count}人`, exact: true }).click();
    await expect.poll(listCount).toBe(count);
  }
  pass('ADD01/02: Original sections and four exact drilldown sets');
  await page.getByLabel('筛选结果所属抖音账号').selectOption('A2');
  await expect.poll(listCount).toBe(12);
  await page.getByLabel('筛选潜客任务').selectOption('T3');
  await expect.poll(listCount).toBe(9);
  await page.getByRole('button', {name: '今日',exact:true}).click();
  assert.ok((await listCount()) <= 9);
  pass('ADD03: Account/date/task combined filtering');
  await open('/results?account=A1&task=T1&stage=analyzed&q=DEMO-USER-T1-0001');
  await page.getByRole('button', {name:'查看演示用户·T1-0001详情',exact:true}).click();
  const dialog = page.getByRole('dialog');
  await dialog.waitFor();
  for (const text of ['客户信息','发现来源与匹配依据','私信与回复记录','留资信息与依据','实际发送内容','对方回复原文','演示数据']) assert.ok((await dialog.innerText()).includes(text));
  assert.equal(await dialog.locator('.nc-evidence').count(), 2);
  assert.equal(await dialog.locator('.nc-message').count(), 4);
  await dialog.getByText('查看发送前计划话术（与最终内容不同）').first().click();
  assert.ok((await dialog.innerText()).includes('看到你关注'));
  const scroll = await page.evaluate(()=>scrollY);
  await page.keyboard.press('Escape');
  assert.equal(await page.getByRole('dialog').count(),0);
  assert.equal(await page.evaluate(()=>scrollY),scroll);
  assert.equal(await page.getByLabel('搜索潜客昵称或平台账号标识').inputValue(),'DEMO-USER-T1-0001');
  pass('ADD04/05/06/07/09/12/14/18: Identity, duplicate evidence, timeline, original plan, demo labels and drawer restore');
  for (const [serial,label] of [['0141','发送失败'],['0142','状态待确认'],['0143','待发送']]) {
    await open(`/results?account=A1&task=T1&q=DEMO-USER-T1-${serial}`);
    assert.ok((await page.locator('.nc-customer-table tbody').innerText()).includes(label));
    await page.locator('.nc-customer-table').getByRole('button',{name:/查看.*详情/}).click();
    assert.ok((await page.getByRole('dialog').innerText()).includes(label));
    await page.keyboard.press('Escape');
  }
  pass('ADD10/11: Failed, unknown and queued sends stay distinct');
  await open('/results?account=A1&task=T1&stage=leads');
  await page.locator('.nc-customer-table').getByRole('button',{name:/查看.*详情/}).first().click();
  assert.ok((await page.getByRole('dialog').innerText()).includes('DEMO_WX_'));
  assert.ok((await page.getByRole('dialog').innerText()).includes('模拟留资'));
  await page.keyboard.press('Escape');
  pass('ADD13: Leads have linked fictional evidence');
  await open('/work/T1');
  await page.getByRole('button',{name:'查看本轮潜客',exact:true}).click();
  assert.ok(new URL(page.url()).searchParams.get('execution'));
  assert.equal(new URL(page.url()).searchParams.get('account'),'A1');
  assert.equal(new URL(page.url()).searchParams.get('task'),'T1');
  assert.ok((await listCount())>0);
  await page.getByRole('button',{name:'返回原任务详情'}).click();
  assert.equal(new URL(page.url()).pathname,'/work/T1');
  pass('ADD15: Execution drilldown and explicit task return');
  await page.getByRole('button',{name:'暂停任务',exact:true}).click();
  const stored = await page.evaluate(()=>localStorage.getItem('sales-agent-demo-v1'));
  assert.ok(stored);
  const state=JSON.parse(stored);
  const history=JSON.stringify(state.customers);
  await open('/chat?task=T1');
  await page.getByText('预览示例话术与沟通规则',{exact:true}).click();
  assert.ok((await page.locator('.message-preview').innerText()).includes('杭州医美咨询顾问'));
  await page.getByLabel('本任务沟通策略（仅影响后续内容）').fill('温和简洁，先说明资料，不催促');
  await page.getByRole('button',{name:'确认调整',exact:true}).click();
  const updated=await page.evaluate(()=>JSON.parse(localStorage.getItem('sales-agent-demo-v1')));
  assert.equal(updated.tasks.find(t=>t.id==='T1').communicationStrategy,'温和简洁，先说明资料，不催促');
  assert.equal(JSON.stringify(updated.customers),history);
  pass('ADD08/16: Preview and confirmed strategy update preserve all historical records');
  await open('/knowledge');
  await page.getByRole('button',{name:'编辑产品：热玛吉'}).click();
  await page.getByRole('dialog').getByLabel('简要介绍').fill('更新后的演示产品介绍，仅供基础咨询。');
  await page.getByRole('button',{name:'保存资料',exact:true}).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  const afterKnowledge=await page.evaluate(()=>JSON.parse(localStorage.getItem('sales-agent-demo-v1')));
  assert.equal(JSON.stringify(afterKnowledge.customers),history);
  assert.deepEqual(afterKnowledge.knowledge.A2,updated.knowledge.A2);
  await open('/chat?task=T1');
  await page.getByText('预览示例话术与沟通规则',{exact:true}).click();
  assert.ok((await page.locator('.message-preview blockquote').innerText()).includes('更新后的演示产品介绍'));
  pass('ADD16: Knowledge product edit changes new preview, preserves history and other accounts');
  await page.reload();
  assert.ok((await page.locator('.sidebar nav').innerText()).includes('提需求'));
  assert.equal(await page.locator('.sidebar nav a').count(),5);
  pass('ADD17: Five original navigation entries only');
  await open('/results?account=all');
  await page.screenshot({path:'/tmp/nomi-v11-results-final.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'/tmp/nomi-v11-mobile.png',fullPage:true});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  pass('Responsive layout has no page-level horizontal overflow');
  const legacyContext=await browser.newContext({reducedMotion:'reduce'});
  const legacyPage=await legacyContext.newPage();
  const legacyState={...state,customers:state.customers.map(({id,accountId,taskIds,discoveredAt,target,contactedAt,leadAt,evidence})=>({id,accountId,taskIds,discoveredAt,target,contactedAt,leadAt,evidence}))};
  await legacyPage.addInitScript(value=>localStorage.setItem('sales-agent-demo-v1',value),JSON.stringify(legacyState));
  await legacyPage.goto('http://localhost:5174/results?account=A1&stage=leads');
  await legacyPage.locator('.nc-customer-table').getByRole('button',{name:/查看.*详情/}).first().click();
  assert.ok((await legacyPage.getByRole('dialog').innerText()).includes('原始'));
  assert.ok((await legacyPage.getByRole('dialog').innerText()).includes('演示对话记录'));
  assert.equal(await legacyPage.locator('.nc-message').count(),0);
  await legacyPage.goto('http://localhost:5174/results?account=A1&task=T1&execution=E-T1-1');
  assert.ok((await legacyPage.locator('.nc-incomplete').innerText()).includes('数据尚未完整'));
  await legacyContext.close();
  pass('Legacy saved data retained with incomplete detail notice, never fabricated messages');
  assert.deepEqual(errors,[]);
  pass('No browser runtime errors');
  await writeFile('/tmp/nomi-v11-browser-checks.json',JSON.stringify({checks,storageCharacters:stored.length},null,2));
  console.log(JSON.stringify({checks,storageCharacters:stored.length},null,2));
} finally { await browser.close(); }
